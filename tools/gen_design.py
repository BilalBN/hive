#!/usr/bin/env python3
"""Generate the Hive design code from design/tokens.json and the Lucide icon map.

Writes:
  app/lib/design/tokens.g.dart   colours, type, spacing, radius, motion for Flutter
  app/lib/design/icons.g.dart    HiveIcons.* constants for the bundled Lucide font
  admin/src/styles/tokens.css    the same tokens as CSS variables

Usage:
  python3 tools/gen_design.py           write the files
  python3 tools/gen_design.py --check   fail if any file is out of date (used in CI)
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOKENS = ROOT / "design" / "tokens.json"
LUCIDE_MAP = ROOT / "design" / "lucide-icons.json"
OUT_DART_TOKENS = ROOT / "app" / "lib" / "design" / "tokens.g.dart"
OUT_DART_ICONS = ROOT / "app" / "lib" / "design" / "icons.g.dart"
OUT_CSS = ROOT / "admin" / "src" / "styles" / "tokens.css"

HEADER = "GENERATED by tools/gen_design.py from {src}. Do not edit by hand."

DART_RESERVED = {
    "abstract", "as", "assert", "async", "await", "break", "case", "catch", "class", "const",
    "continue", "covariant", "default", "deferred", "do", "dynamic", "else", "enum", "export",
    "extends", "extension", "external", "factory", "false", "final", "finally", "for",
    "function", "get", "hide", "if", "implements", "import", "in", "interface", "is", "late",
    "library", "mixin", "new", "null", "on", "operator", "part", "required", "rethrow",
    "return", "set", "show", "static", "super", "switch", "sync", "this", "throw", "true",
    "try", "typedef", "var", "void", "while", "with", "yield", "hashCode", "runtimeType",
    "toString", "noSuchMethod",
}


def camel(name: str) -> str:
    parts = re.split(r"[-_\s]+", name)
    out = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    if out[:1].isdigit():
        out = "i" + out
    return out


def kebab(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()


def dart_color(hex_: str) -> str:
    return f"Color(0xFF{hex_.lstrip('#').upper()})"


def gen_dart_tokens(t: dict) -> str:
    colors = t["color"]
    keys = list(colors["dark"].keys())
    assert keys == list(colors["light"].keys()), "dark and light must have the same keys"
    lines = [
        f"// {HEADER.format(src='design/tokens.json')}",
        "// ignore_for_file: public_member_api_docs",
        "",
        "import 'package:flutter/widgets.dart';",
        "",
        "/// One theme's colours. Use through `HiveTheme.of(context)`.",
        "@immutable",
        "class HivePalette {",
        "  const HivePalette({",
        *[f"    required this.{k}," for k in keys],
        "  });",
        "",
        *[f"  final Color {k};" for k in keys],
        "",
    ]
    for mode in ("dark", "light"):
        lines.append(f"  static const {mode} = HivePalette(")
        lines += [f"    {k}: {dart_color(v)}," for k, v in colors[mode].items()]
        lines.append("  );")
        lines.append("")
    lines.append("}")
    lines.append("")

    font = t["font"]
    fallbacks = ", ".join(f"'{f}'" for f in font["fallbacks"])
    lines += [
        "/// Type scale. Inter with Malayalam and Devanagari fallbacks for song titles.",
        "abstract final class HiveType {",
        f"  static const String family = '{font['family']}';",
        f"  static const List<String> fallbacks = [{fallbacks}];",
        "",
    ]
    for name, s in t["type"].items():
        size = s["size"]
        height = round(s["lineHeight"] / size, 4)
        parts = [
            "fontFamily: family",
            "fontFamilyFallback: fallbacks",
            f"fontSize: {size}",
            f"height: {height}",
            f"fontWeight: FontWeight.w{s['weight']}",
            "fontFeatures: [FontFeature.tabularFigures()]",
        ]
        if "letterSpacing" in s:
            parts.append(f"letterSpacing: {round(s['letterSpacing'] * size, 3)}")
        lines.append(f"  static const TextStyle {name} = TextStyle({', '.join(parts)});")
    lines += ["}", ""]

    lines.append("/// Spacing on a 4-point grid.")
    lines.append("abstract final class HiveSpace {")
    lines += [f"  static const double {k} = {v};" for k, v in t["space"].items()]
    lines += ["}", "", "/// Corner radii.", "abstract final class HiveRadius {"]
    lines += [f"  static const double {k} = {v};" for k, v in t["radius"].items()]
    lines += ["}", "", "/// Animation durations.", "abstract final class HiveMotion {"]
    lines += [
        f"  static const Duration {k} = Duration(milliseconds: {v});"
        for k, v in t["motion"].items()
    ]
    lines += ["}", ""]
    return "\n".join(lines)


def gen_dart_icons(icon_map: dict[str, int], family: str) -> str:
    lines = [
        f"// {HEADER.format(src='design/lucide-icons.json')}",
        "// Lucide icons (ISC licence), drawn from the bundled Lucide font.",
        "// ignore_for_file: constant_identifier_names, public_member_api_docs",
        "",
        "import 'package:flutter/widgets.dart';",
        "",
        "abstract final class HiveIcons {",
        f"  static const String fontFamily = '{family}';",
        "",
    ]
    seen: set[str] = set()
    for name in sorted(icon_map):
        ident = camel(name)
        if ident in DART_RESERVED:
            ident += "Icon"
        if ident in seen:
            raise SystemExit(f"duplicate icon identifier {ident} from {name}")
        seen.add(ident)
        lines.append(
            f"  static const IconData {ident} = IconData(0x{icon_map[name]:x}, fontFamily: fontFamily);"
        )
    lines += ["}", ""]
    return "\n".join(lines)


def gen_css(t: dict) -> str:
    def block(mode: str) -> list[str]:
        return [f"  --hv-{kebab(k)}: {v};" for k, v in t["color"][mode].items()]

    font = t["font"]
    stack = ", ".join(
        [f'"{font["family"]}"']
        + [f'"{re.sub(r"(?<!^)(?=[A-Z])", " ", f)}"' for f in font["fallbacks"]]
        + ["system-ui", "sans-serif"]
    )
    lines = [
        f"/* {HEADER.format(src='design/tokens.json')} */",
        "",
        ":root {",
        "  color-scheme: dark;",
        *block("dark"),
        f"  --hv-font: {stack};",
    ]
    for name, s in t["type"].items():
        k = kebab(name)
        lines.append(f"  --hv-type-{k}: {s['weight']} {s['size']}px/{s['lineHeight']}px var(--hv-font);")
    lines += [f"  --hv-space-{k}: {v}px;" for k, v in t["space"].items()]
    lines += [f"  --hv-radius-{k}: {v}px;" for k, v in t["radius"].items()]
    lines += [f"  --hv-motion-{k}: {v}ms;" for k, v in t["motion"].items()]
    lines += [
        "}",
        "",
        "@media (prefers-color-scheme: light) {",
        '  :root:not([data-theme="dark"]) {',
        "    color-scheme: light;",
        *["  " + line for line in block("light")],
        "  }",
        "}",
        "",
        ':root[data-theme="light"] {',
        "  color-scheme: light;",
        *block("light"),
        "}",
        "",
    ]
    return "\n".join(lines)


def outputs() -> dict[Path, str]:
    tokens = json.loads(TOKENS.read_text(encoding="utf-8"))
    icon_map = {k: int(v) for k, v in json.loads(LUCIDE_MAP.read_text(encoding="utf-8")).items()}
    return {
        OUT_DART_TOKENS: gen_dart_tokens(tokens),
        OUT_DART_ICONS: gen_dart_icons(icon_map, tokens["font"]["icons"]),
        OUT_CSS: gen_css(tokens),
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = ap.parse_args()
    stale = []
    for path, content in outputs().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("Out of date (run python3 tools/gen_design.py):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
